def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=20260902)
    parser.add_argument("--out", default=str(HERE / "ground-truth.jsonl"))
    parser.add_argument("--manifest", default=str(HERE / "manifest.json"))
    args = parser.parse_args(argv)

    items, manifest = generate(args.seed)

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as handle:
        for item in items:
            handle.write(json.dumps(item, sort_keys=True, ensure_ascii=False) + "\n")

    digest = hashlib.sha256(out_path.read_bytes()).hexdigest()
    manifest["ground_truth_sha256"] = digest
    manifest["ground_truth_file"] = out_path.name
    manifest["drift_sample_size"] = DRIFT_SAMPLE_SIZE
    Path(args.manifest).write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    # A public sample that can be published without the private split.
    sample_dir = HERE / "sample"
    sample_dir.mkdir(exist_ok=True)
    with (sample_dir / "ground-truth.jsonl").open("w", encoding="utf-8") as handle:
        for item in items:
            if item["split"] == "public_sample":
                handle.write(json.dumps(item, sort_keys=True, ensure_ascii=False) + "\n")

    print(f"wrote {len(items)} items to {out_path}")
    print(f"sha256 {digest}")
    print("populations " + json.dumps(manifest["populations"]))
    print("tiers      " + json.dumps(manifest["tier_counts"]))
    print("work types " + json.dumps(manifest["work_type_counts"]))
    print("lifecycle  " + json.dumps(manifest["lifecycle_counts"]))
    print("splits     " + json.dumps(manifest["split_counts"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
