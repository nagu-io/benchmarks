def stream(seed: int, *parts: str) -> random.Random:
    """A named deterministic stream, so adding a field never moves another one."""
    key = f"{seed}|" + "|".join(parts)
    digest = hashlib.sha256(key.encode("utf-8")).hexdigest()
    return random.Random(int(digest[:16], 16))


def largest_remainder(total: int, weights: dict) -> dict:
    """Split `total` across `weights` so the parts sum exactly to `total`."""
    raw = {k: total * w for k, w in weights.items()}
    floors = {k: int(v) for k, v in raw.items()}
    remainder = total - sum(floors.values())
    order = sorted(raw, key=lambda k: (-(raw[k] - floors[k]), str(k)))
    for k in order[:remainder]:
        floors[k] += 1
    return floors


def invalid_pan(rng: random.Random) -> str:
    """PAN-shaped and structurally impossible: position 4 holds a holder-type letter
    drawn from a fixed set in the real scheme, and 'X' is not in that set."""
    letters = "ABCDEFGHJKLMNPQRSTUVWXYZ"
    head = "".join(rng.choice(letters) for _ in range(3))
    return f"{head}X{rng.choice(letters)}{rng.randint(0, 9999):04d}{rng.choice(letters)}"


def invalid_gstin(rng: random.Random) -> str:
    """GSTIN-shaped and structurally impossible: the leading state code is '00',
    which is not an allocated state code."""
    return f"00{invalid_pan(rng)}{rng.randint(1, 9)}Z{rng.choice('ABCDEFGHJKLMNPQRSTUVWXYZ')}"


def invalid_doc_number(rng: random.Random, prefix: str) -> str:
    """Document numbers carry a 'ZZ' block that no issuing scheme in the model uses."""
    return f"{prefix}-ZZ{rng.randint(100000, 999999)}"


def money(rng: random.Random, low: float, high: float) -> float:
    return round(rng.uniform(low, high), 2)


