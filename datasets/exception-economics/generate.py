#!/usr/bin/env python3
"""Exception Economics dataset v1.0.0 — seeded generator.

Produces 2,000 synthetic back-office work items with ground truth, a difficulty tier
assigned from recorded parameters per charter section 4.4, and the attributes the
labour model in `labour-model.yaml` needs to price them.

Three kinds of work item:

  ticket_triage      a support ticket to be categorised, prioritised and routed
  kyc_case           a know-your-customer case to be passed, referred or rejected
  invoice_po_recon   an invoice to be matched against one or more purchase orders

Everything in the output is synthetic. Every company, person, address and identifier
is generated by this file. Identifiers are format-shaped and deliberately invalid by
construction, per charter 6.3, and `validate.py` proves it.

Each item also carries a `reference_policy` block. That block is a synthetic
stand-in for a system's decision: a proposed outcome and a confidence, drawn from the
item's tier. It is a property of this dataset, not a measurement of any model, and
`score.py` says so on every table it produces. A real system's predictions are
dropped in through the interface documented in README.md.

Usage:
    python3 generate.py --seed 20260902
    python3 generate.py --seed 20260902 --out ground-truth.jsonl

Deterministic: the same seed produces byte-identical output.
"""

