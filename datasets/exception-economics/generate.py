def plan_items(seed: int) -> list[dict]:
    """Decide work type, tier and population for every item before any content is
    generated, so that a change to one item's content cannot move another's tier."""
    plan: list[dict] = []
    work_counts = largest_remainder(BASELINE_ITEMS, BASELINE_WORK_MIX)
    for work_type in sorted(work_counts):
        tier_counts = largest_remainder(work_counts[work_type], BASELINE_TIER_MIX)
        for tier in sorted(tier_counts):
            for _ in range(tier_counts[tier]):
                plan.append({"work_type": work_type, "tier": tier,
                             "population": "baseline", "shift_driver": None})
    for driver in sorted(SHIFT_PLAN):
        work_type, count = SHIFT_PLAN[driver]
        for _ in range(count):
            plan.append({"work_type": work_type, "tier": 5,
                         "population": "shifted", "shift_driver": driver})

    if len(plan) != TOTAL_ITEMS:
        raise SystemExit(f"plan produced {len(plan)} items, expected {TOTAL_ITEMS}")

    order = stream(seed, "plan-order")
    order.shuffle(plan)
    return plan


def assign_splits(items: list[dict], seed: int) -> None:
    """Stratified across work type and tier, drawn with a named stream, so the split
    is part of the ground truth rather than a property of which folder exists."""
    for item in items:
        item["split"] = "open"
    buckets: dict[tuple, list[int]] = {}
    for idx, item in enumerate(items):
        buckets.setdefault((item["work_type"], item["tier"]), []).append(idx)

    for split_name, size in SPLIT_PLAN.items():
        rng = stream(seed, "split", split_name)
        weights = {k: len(v) / len(items) for k, v in buckets.items()}
        counts = largest_remainder(size, weights)
        for key in sorted(buckets, key=lambda k: (str(k[0]), k[1])):
            available = [i for i in buckets[key] if items[i]["split"] == "open"]
            take = min(counts.get(key, 0), len(available))
            for idx in rng.sample(available, k=take):
                items[idx]["split"] = split_name


def generate(seed: int) -> tuple[list[dict], dict]:
    plan = plan_items(seed)
    items: list[dict] = []

    for index, entry in enumerate(plan):
        item_id = f"EE-{index + 1:04d}"
        work_type = entry["work_type"]
        tier = entry["tier"]
        shifted = entry["population"] == "shifted"

        content_rng = stream(seed, "content", item_id)
        attributes, ground_truth = BUILDERS[work_type](content_rng, tier, shifted)
        params = tier_parameters(tier, content_rng, shifted)

        received = datetime.combine(WINDOW_START, time.min) + timedelta(
            days=content_rng.randrange(WINDOW_DAYS),
            minutes=content_rng.randrange(0, 24 * 60),
        )

        # Lifecycle. Drawn on its own stream so that adding a content field never
        # moves an item between admitted, rejected and in flight.
        life_rng = stream(seed, "lifecycle", item_id)
        roll = life_rng.random()
        lifecycle = "admitted"
        exclusion_reason = None
        if roll < P_PRE_PROCESSING_REJECT:
            lifecycle = "pre_processing_rejected"
            exclusion_reason = life_rng.choice(PRE_PROCESSING_RULES)
        elif roll < P_PRE_PROCESSING_REJECT + P_UPSTREAM_FAILURE:
            lifecycle = "upstream_failure"
            exclusion_reason = "upstream_system_unavailable"
        elif roll < P_PRE_PROCESSING_REJECT + P_UPSTREAM_FAILURE + P_IN_FLIGHT:
            lifecycle = "in_flight"
            exclusion_reason = "open_at_window_close"

        # Reference decision policy. Synthetic. Not a model output.
        pol_rng = stream(seed, "reference-policy", item_id)
        p_correct = P_CORRECT_BY_TIER[tier]
        if shifted:
            p_correct *= SHIFTED_CORRECTNESS_MULTIPLIER
        correct = pol_rng.random() < p_correct

        processing_failure = pol_rng.random() < P_PROCESSING_FAILURE
        validation_failure = pol_rng.random() < P_VALFAIL_BY_TIER[tier]
        policy_flag = pol_rng.random() < P_FLAG_BY_TIER[tier]

        category_pool = (SHIFTED_TICKET_CATEGORIES if shifted
                         else BASELINE_TICKET_CATEGORIES)
        if processing_failure:
            proposed, error_class = None, None
            confidence = None
        elif correct:
            proposed, error_class = ground_truth["outcome"], None
            confidence = reference_confidence(pol_rng, tier, True, shifted)
        else:
            proposed = wrong_outcome(work_type, ground_truth, attributes, pol_rng,
                                     category_pool)
            error_class = classify_error(work_type, ground_truth["outcome"], proposed,
                                         attributes)
            confidence = reference_confidence(pol_rng, tier, False, shifted)
            if error_class is None:
                # The wrong-outcome draw happened to reproduce the ground truth.
                # It is then not a wrong automation, and is recorded as correct.
                correct = True

        if processing_failure:
            forced_code = "FAIL"
        elif validation_failure:
            forced_code = "VALFAIL"
        elif policy_flag:
            forced_code = "FLAG"
        else:
            forced_code = None

        exception_type_if_routed = EXCEPTION_TYPE[(work_type, forced_code or "LOWCONF")]

        items.append({
            "item_id": item_id,
            "dataset_version": DATASET_VERSION,
            "schema_version": SCHEMA_VERSION,
            "synthetic": True,
            "work_type": work_type,
            "tier": tier,
            "tier_parameters": params,
            "population": entry["population"],
            "shift_driver": entry["shift_driver"],
            "received_at": received.isoformat(timespec="minutes"),
            "lifecycle": lifecycle,
            "exclusion_reason": exclusion_reason,
            "attributes": attributes,
            "ground_truth": ground_truth,
            "labour_keys": {
                "work_type": work_type,
                "tier": tier,
                "forced_entry_code": forced_code,
                "exception_type_if_routed": exception_type_if_routed,
                "error_class_if_wrong": error_class,
            },
            "reference_policy": {
                "note": ("Synthetic decision-policy stand-in generated with the item. "
                         "A property of this dataset, not a measurement of any model."),
                "proposed_outcome": proposed,
                "correct": None if processing_failure else correct,
                "confidence": confidence,
                "processing_failure": processing_failure,
                "validation_failure": validation_failure,
                "policy_flag": policy_flag,
            },
        })

    assign_splits(items, seed)

    manifest = build_manifest(items, seed)
    return items, manifest


def build_manifest(items: list[dict], seed: int) -> dict:
    def tally(key):
        out: dict = {}
        for item in items:
            out[str(item[key])] = out.get(str(item[key]), 0) + 1
        return dict(sorted(out.items()))

    baseline = [i for i in items if i["population"] == "baseline"]
    shifted = [i for i in items if i["population"] == "shifted"]

    return {
        "dataset": "exception-economics",
        "dataset_version": DATASET_VERSION,
        "schema_version": SCHEMA_VERSION,
        "generator_version": GENERATOR_VERSION,
        "charter_version": CHARTER_VERSION,
        "seed": seed,
        "synthetic": True,
        "items": len(items),
        "populations": {"baseline": len(baseline), "shifted": len(shifted)},
        "work_type_counts": tally("work_type"),
        "tier_counts": tally("tier"),
        "lifecycle_counts": tally("lifecycle"),
        "split_counts": tally("split"),
        "shift_drivers": {
            driver: sum(1 for i in shifted if i["shift_driver"] == driver)
            for driver in sorted(SHIFT_PLAN)
        },
        "unseen_categories": {
            "ticket_categories": SHIFTED_TICKET_CATEGORIES,
            "kyc_sources": SHIFTED_KYC_SOURCES,
            "vendor_formats": SHIFTED_VENDOR_FORMATS,
        },
        "baseline_categories": {
            "ticket_categories": BASELINE_TICKET_CATEGORIES,
            "kyc_sources": BASELINE_KYC_SOURCES,
            "vendor_formats": BASELINE_VENDOR_FORMATS,
        },
        "drift_steps": DRIFT_STEPS,
        "window": {"start": WINDOW_START.isoformat(), "days": WINDOW_DAYS},
        "reference_policy_parameters": {
            "note": ("Parameters of the synthetic decision-policy stand-in. Not a "
                     "claim about any model."),
            "p_correct_by_tier": P_CORRECT_BY_TIER,
            "shifted_correctness_multiplier": SHIFTED_CORRECTNESS_MULTIPLIER,
            "p_valfail_by_tier": P_VALFAIL_BY_TIER,
            "p_flag_by_tier": P_FLAG_BY_TIER,
            "p_processing_failure": P_PROCESSING_FAILURE,
            "p_pre_processing_reject": P_PRE_PROCESSING_REJECT,
            "p_upstream_failure": P_UPSTREAM_FAILURE,
            "p_in_flight": P_IN_FLIGHT,
        },
    }


