def reference_confidence(rng: random.Random, tier: int, correct: bool,
                         shifted: bool) -> float:
    """Synthetic confidence. High tiers are overconfident when wrong; shifted items
    are more overconfident still, which is the behaviour the drift simulation is
    built to make visible. A parameter of the dataset, not a model measurement."""
    if correct:
        base = 0.55 + 0.45 * rng.betavariate(5.0, 1.6)
        if tier >= 4:
            base -= 0.06
        if shifted:
            base -= 0.04
    else:
        if shifted:
            base = 0.55 + 0.45 * rng.betavariate(3.0, 1.8)
        elif tier >= 4:
            base = 0.45 + 0.55 * rng.betavariate(2.6, 2.0)
        else:
            base = 0.35 + 0.65 * rng.betavariate(2.0, 3.0)
    return round(min(0.999, max(0.010, base)), 3)


