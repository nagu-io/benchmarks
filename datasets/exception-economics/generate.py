    sources = rng.sample(pool, k=min(n_sources, len(pool)))
    outcome = rng.choices(KYC_OUTCOMES, weights=[0.72, 0.22, 0.06])[0]
    reason = rng.choice(KYC_REFER_REASONS) if outcome != "pass" else None
    attributes = {
        "applicant_name": person(rng),
        "applicant_city": rng.choice(CITIES),
        "entity_type": rng.choice(["individual", "individual", "sole_trader",
                                   "private_company"]),
        "sources_supplied": sources,
        "identity_number": invalid_pan(rng),
        "document_number": invalid_doc_number(rng, "KYC"),
        "screening_lists_checked": rng.randint(1, 3),
        "name_variants_present": rng.randint(1, 3) if tier >= 3 else 1,
        "address_matches_across_sources": tier <= 2 or rng.random() < 0.55,
        "beneficial_owners": 0 if tier <= 2 else rng.randint(0, 3),
    }
    ground_truth = {
        "decision": outcome,
        "reason_code": reason,
        "outcome": kyc_outcome(outcome, reason),
    }
    return attributes, ground_truth


