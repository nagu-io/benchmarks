"""Intent catalogue for the Honest Containment dataset.

Synthetic. Sixty intents, fifteen per domain, each tied to the policy documents that
decide it and to a ground-truth resolution written as a code plus an English statement
plus a list of required actions.

Fields
------
key                 stable identifier, used in ids and in the agent scope file
label               one line, used in reports and transcripts
docs                the policy documents that must be in the agent's pack
in_scope            whether the reference agent is configured for this intent at all
escalates           the intent is itself a policy trigger for escalation (3.11.2)
escalation_dest     destination queue named in the domain's escalation matrix
resolution_code     the ground-truth outcome code, checked by rule
resolution          the ground-truth resolution in one or two sentences
actions             required actions, each checked by rule or by the judge
quote               keys in the policy value index the agent must state correctly
must_not            named prohibited moves, each checked by rule or by the judge
open_en             the caller's opening line
detail_en           the caller's follow-up, with {} parameters filled per scenario
turns               (minimum, maximum) turns a competent agent needs, ours to state
"""

from __future__ import annotations


def I(key, label, docs, resolution_code, resolution, actions, open_en, detail_en,
      turns, quote=(), must_not=(), in_scope=True, escalates=False, escalation_dest=None):
    return {
        "key": key,
        "label": label,
        "docs": list(docs),
        "in_scope": in_scope,
        "escalates": escalates,
        "escalation_dest": escalation_dest,
        "resolution_code": resolution_code,
        "resolution": resolution,
        "actions": list(actions),
        "quote": list(quote),
        "must_not": list(must_not),
        "open_en": open_en,
        "detail_en": detail_en,
        "turns": turns,
    }


